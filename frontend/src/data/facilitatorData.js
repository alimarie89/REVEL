  // Helper function to get facilitator by name or ID
  getFacilitator(nameOrId) {
    // Try to find by ID first
    if (this.facilitators[nameOrId]) {
      return this.facilitators[nameOrId];
    }
    
    // Try to find by name
    for (const [id, fac] of Object.entries(this.facilitators)) {
      if (fac.name.toLowerCase() === nameOrId.toLowerCase()) {
        return fac;
      }
    }
    
    return null;
  },

  // Get multiple facilitators
  getFacilitators(facilitatorNames) {
    if (!facilitatorNames || facilitatorNames.length === 0) return [];
    return facilitatorNames
      .map(name => this.getFacilitator(name))
      .filter(fac => fac !== null);
  }
